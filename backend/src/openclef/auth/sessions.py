"""Server-side session management.

The session cookie carries a signed payload `{user_id, session_id, iat}`
generated by `itsdangerous`. The `session_id` is opaque (a random URL-safe
token); Redis stores a *revocation set* keyed `revoked:<session_id>` whose
mere presence marks the session as invalid. Active sessions don't live in
Redis at all, which keeps the storage cost proportional to logout activity
rather than session count.

Why not just store the whole session in Redis? Because sessions are
read on every authed request; bouncing every read off Redis would
double the per-request latency for a feature (revocation) that's
exercised maybe once per session lifetime. Letting the cookie carry
identity and using Redis only for revocation is the standard pattern.
"""
from __future__ import annotations

import secrets
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone

from itsdangerous import BadSignature, SignatureExpired, URLSafeTimedSerializer
from redis.asyncio import Redis

from openclef.config import get_settings


SESSION_COOKIE_NAME = "openclef_session"


class SessionConfigError(RuntimeError):
    """Raised when no secret_key is configured in a non-dev environment."""


@dataclass(frozen=True)
class SessionPayload:
    user_id: uuid.UUID
    session_id: str
    issued_at: datetime


def _serializer() -> URLSafeTimedSerializer:
    s = get_settings()
    if not s.secret_key:
        if s.env != "dev":
            raise SessionConfigError(
                "OPENCLEF_SECRET_KEY is required when OPENCLEF_ENV is not 'dev'."
            )
        # Dev-only: deterministic-ish dev key. Restarts invalidate all
        # sessions, which we accept as a feature in dev.
        return URLSafeTimedSerializer("openclef-dev-secret-do-not-use-in-prod", salt="session")
    return URLSafeTimedSerializer(s.secret_key, salt="session")


def _max_age_seconds() -> int:
    return get_settings().session_max_age_days * 24 * 60 * 60


def issue_session(user_id: uuid.UUID) -> tuple[str, SessionPayload]:
    """Mint a new session cookie value + the payload it encodes."""
    payload = SessionPayload(
        user_id=user_id,
        session_id=secrets.token_urlsafe(32),
        issued_at=datetime.now(timezone.utc),
    )
    cookie = _serializer().dumps(
        {
            "user_id": str(payload.user_id),
            "session_id": payload.session_id,
            "iat": payload.issued_at.isoformat(),
        }
    )
    return cookie, payload


def parse_session(cookie_value: str) -> SessionPayload | None:
    """Verify signature + max-age. Returns None on any failure (don't leak why)."""
    try:
        raw = _serializer().loads(cookie_value, max_age=_max_age_seconds())
    except (BadSignature, SignatureExpired):
        return None
    try:
        return SessionPayload(
            user_id=uuid.UUID(raw["user_id"]),
            session_id=raw["session_id"],
            issued_at=datetime.fromisoformat(raw["iat"]),
        )
    except (KeyError, ValueError):
        return None


def _revoke_key(session_id: str) -> str:
    return f"revoked:{session_id}"


async def is_revoked(redis: Redis, session_id: str) -> bool:
    return await redis.exists(_revoke_key(session_id)) == 1


async def revoke(redis: Redis, session_id: str) -> None:
    """Mark a session_id as revoked. TTL = max session lifetime so the
    revocation entry expires at the same time the cookie would.
    """
    await redis.set(_revoke_key(session_id), "1", ex=_max_age_seconds())
